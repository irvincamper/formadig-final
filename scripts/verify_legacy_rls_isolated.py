"""Amplía el laboratorio existente con registros legacy ficticios y recuperación.

No conecta a Supabase. Auth/JWT simulados; SQL/RLS y triggers PostgreSQL reales.
"""
import json
from pathlib import Path
from verify_rls_isolated import main, USER, LEGACY, OTHER

ROOT=Path(__file__).resolve().parents[1]
TABLES=('traslados','desayunos_frios','desayunos_calientes','desayunos_eaeyd')
A=OTHER
B='00000000-0000-0000-0000-000000000099'
RA='10000000-0000-0000-0000-000000000001'
RB='10000000-0000-0000-0000-000000000002'
RC='10000000-0000-0000-0000-000000000003'


def scenario(sql,check,actor):
    # Sólo se sustituye una tabla del clúster de laboratorio, nunca de DIF.
    sql('DROP TABLE public.traslados;')
    for table in TABLES:
        sql(f"CREATE TABLE public.{table}(id uuid PRIMARY KEY,registrado_por uuid REFERENCES public.perfiles(id),estatus text DEFAULT 'Pendiente',localidad text,usuario_admin uuid);")
    sql("CREATE TABLE public.sms_logs(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,fecha timestamptz DEFAULT now(),telefono text,mensaje text,estatus text,error text,enviado_por text);"
        "CREATE TABLE public.notificaciones(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,usuario_id uuid REFERENCES public.perfiles(id),titulo text,mensaje text,leida boolean DEFAULT false,created_at timestamptz DEFAULT now());")
    inventory=json.loads((ROOT/'tests_clinical/fixtures/legacy_policy_inventory.json').read_text(encoding='utf-8'))
    for table in (*TABLES,'sms_logs','notificaciones'):
        sql(f'GRANT ALL ON public.{table} TO anon,authenticated;')
    for p in inventory:
        roles=','.join('PUBLIC' if r=='public' else '"'+r+'"' for r in p['roles'])
        query='CREATE POLICY "'+p['policyname'].replace('"','""')+'" ON public.'+p['tablename']+' FOR '+p['cmd']+' TO '+roles
        if p['qual']: query+=' USING ('+p['qual']+')'
        if p['with_check']: query+=' WITH CHECK ('+p['with_check']+')'
        sql(query+';')
    sql((ROOT/'tests_clinical/fixtures/legacy_notification_trigger.sql').read_text(encoding='utf-8'))
    for table,suffix in zip(TABLES,('traslados','frios','calientes','eaeyd')):
        sql(f'CREATE TRIGGER trigger_notif_{suffix} AFTER UPDATE ON public.{table} FOR EACH ROW EXECUTE FUNCTION public.crear_notificacion_por_cambio_estatus();')
    # El laboratorio original termina con USER dentista y LEGACY admin_traslados.
    roles=['admin']*3+['admin_traslados']*3+['admin_desayunos']*2+['psicologo']
    users={}
    for i,role in enumerate(roles,20):
        uid='00000000-0000-0000-0000-'+str(i).zfill(12)
        sql(f"INSERT INTO auth.users VALUES('{uid}','{{\"role\":\"{role}\"}}','{{}}');")
        users[role]=uid
    users['dentista']=USER
    sql(f"INSERT INTO auth.users VALUES('{B}','{{}}','{{}}');")
    migration=next((ROOT/'supabase/migrations').glob('*_formadig_rls_modulos_legacy.sql')).read_text(encoding='utf-8')
    try:
        sql(migration);raise AssertionError('Corte no aprobado')
    except RuntimeError as error:
        assert 'Falta revisar respaldo' in str(error)
    sql("SET formadig.legacy_cutover='approved';"+migration)
    for table in TABLES:
        sql(f"INSERT INTO public.{table}(id,registrado_por,localidad) VALUES('{RA}','{A}','LAB A'),('{RB}','{B}','LAB B'),('{RC}','{users['psicologo']}','LAB clinical owner');")
    for role,uid in users.items():
        for table in TABLES:
            allowed=role=='admin' or role==('admin_traslados' if table=='traslados' else 'admin_desayunos')
            expected=','.join((RA,RB,RC)) if allowed else ''
            query=f"SELECT coalesce(string_agg(id::text,',' ORDER BY id),'') FROM public.{table}"
            # Un conjunto vacío se expresa como marcador para el comprobador existente.
            query=query.replace("coalesce(string_agg(id::text,',' ORDER BY id),'')","coalesce(string_agg(id::text,',' ORDER BY id),'EMPTY')")
            check(role+' filas concretas '+table,actor(role,query,user=uid),expected or 'EMPTY')
            if allowed:
                check(role+' actualiza area '+table,actor(role,f"UPDATE public.{table} SET localidad='LAB edit' WHERE id='{RA}' RETURNING localidad",user=uid),'LAB edit')
                check(role+' no reasigna propietario '+table,actor(role,f"UPDATE public.{table} SET registrado_por='{uid}' WHERE id='{RA}'",user=uid),denied=True)
            else:
                check(role+' no actualiza area ajena '+table,actor(role,f"WITH x AS (UPDATE public.{table} SET localidad='x' RETURNING id) SELECT count(*) FROM x",user=uid),'0')
                check(role+' no inserta area ajena '+table,actor(role,f"INSERT INTO public.{table}(id,registrado_por) VALUES(gen_random_uuid(),'{uid}')",user=uid),denied=True)
            check(role+' sin DELETE '+table,actor(role,f'DELETE FROM public.{table}',user=uid),denied=True)
            check(role+' sin TRUNCATE '+table,actor(role,f'TRUNCATE public.{table}',user=uid),denied=True)
    for table in TABLES:
        check('propietario firmado ve su fila '+table,actor('not_a_web_fixture',f'SELECT id FROM public.{table}',user=A),RA)
        check('propietario edita datos propios '+table,actor('not_a_web_fixture',f"UPDATE public.{table} SET localidad='LAB own' WHERE id='{RA}' RETURNING localidad",user=A),'LAB own')
        check('propietario no altera dictamen '+table,actor('not_a_web_fixture',f"UPDATE public.{table} SET estatus='Aprobado' WHERE id='{RA}'",user=A),denied=True)
        check('propietario no crea dictamen aprobado '+table,actor('not_a_web_fixture',f"INSERT INTO public.{table}(id,registrado_por,estatus) VALUES(gen_random_uuid(),'{A}','Aprobado')",user=A),denied=True)
        check('propietario no forja dueño '+table,actor('not_a_web_fixture',f"INSERT INTO public.{table}(id,registrado_por) VALUES(gen_random_uuid(),'{B}')",user=A),denied=True)
        check('propietario crea pendiente '+table,actor('not_a_web_fixture',f"INSERT INTO public.{table}(id,registrado_por) VALUES(gen_random_uuid(),'{A}') RETURNING estatus",user=A),'Pendiente')
        check('anon no lee '+table,actor('admin',f'SELECT * FROM public.{table}',db_role='anon'),denied=True)
        check('Auth anonimo no lee '+table,actor('not_a_web_fixture',f'SELECT count(*) FROM public.{table}',user=A,anonymous=True),'0')
    check('JWT viejo no usa excepción de propietario',actor('psicologo','SELECT count(*) FROM public.traslados',user=users['psicologo'],claim='admin'),'0')
    # UPDATE real del trigger auditado; sólo en el clúster ficticio.
    commit=actor('admin_traslados',f"UPDATE public.traslados SET estatus='Aprobado' WHERE id='{RA}'",user=users['admin_traslados']).replace('ROLLBACK;','COMMIT;')
    sql(commit)
    check('notificación llega al dueño',actor('not_a_web_fixture','SELECT count(*) FROM public.notificaciones',user=A),'1')
    check('otro dueño no ve notificación',actor('not_a_web_fixture','SELECT count(*) FROM public.notificaciones',user=B),'0')
    check('staff no lee mensaje ajeno',actor('admin_traslados','SELECT count(*) FROM public.notificaciones',user=users['admin_traslados']),'0')
    check('dueño marca leída',actor('not_a_web_fixture','UPDATE public.notificaciones SET leida=true RETURNING leida',user=A),'t')
    check('cliente no fabrica notificación',actor('admin_traslados',f"INSERT INTO public.notificaciones(usuario_id,mensaje) VALUES('{A}','spoof')",user=users['admin_traslados']),denied=True)
    check('cliente no reescribe mensaje',actor('not_a_web_fixture',"UPDATE public.notificaciones SET mensaje='spoof'",user=A),denied=True)
    for role,uid in users.items():
        allowed=role in ('admin','admin_traslados','psicologo','dentista')
        check(role+' SMS propio',actor(role,f"INSERT INTO public.sms_logs(enviado_por,mensaje) VALUES('{uid}','LAB only') RETURNING enviado_por",user=uid),uid if allowed else None,denied=not allowed)
        check(role+' no forja remitente',actor(role,f"INSERT INTO public.sms_logs(enviado_por,mensaje) VALUES('{A}','spoof')",user=uid),denied=True)
    sql(f"INSERT INTO public.sms_logs(enviado_por,mensaje) VALUES('{users['psicologo']}','LAB private');")
    check('SMS propio visible',actor('psicologo','SELECT mensaje FROM public.sms_logs',user=users['psicologo']),'LAB private')
    check('SMS ajeno oculto',actor('dentista','SELECT count(*) FROM public.sms_logs',user=USER),'0')
    all_tables=('perfiles','modulo_psicologia','modulo_dental',*TABLES,'sms_logs','notificaciones')
    checksum=lambda t:f"SELECT md5(coalesce(jsonb_agg(to_jsonb(x) ORDER BY to_jsonb(x)::text)::text,'[]')) FROM public.{t} x"
    before={t:sql(checksum(t)).strip() for t in all_tables}
    recovery=(ROOT/'supabase/recovery/formadig_fail_closed.sql').read_text(encoding='utf-8')
    sql(recovery);sql(recovery)
    for table in all_tables:
        check('recuperación conserva contenido '+table,checksum(table),before[table])
        for dbrole in ('anon','authenticated'):
            check('recuperación bloquea '+dbrole+' '+table,actor('admin',f'SELECT * FROM public.{table}',user=users['admin'],db_role=dbrole),denied=True)


if __name__=='__main__': main(after_phase_b=scenario)
